package com.linearity.opentc4.annotations;

import java.lang.annotation.*;

/**
 * Mark when the whole file is generated.
 * Usually you may have to modify the template instead of generated part to actually modify file
 * */
@Documented
@Retention(RetentionPolicy.CLASS)
@Target({ElementType.METHOD, ElementType.FIELD, ElementType.PARAMETER, ElementType.LOCAL_VARIABLE, ElementType.TYPE_USE})
public @interface AutoGeneratedCode {
}
